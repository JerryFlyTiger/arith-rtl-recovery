"""Generates gate-level netlists for the demo (does not use organizer test data, so this directory runs standalone).

    python3 demo/gen_netlists.py

Outputs to `demo/netlists/*.v`; each one is a primitive-gate netlist with `module top(...)`,
in the same format as `testcase/testNN/top_primitive.v`, so it can be fed to the solver directly.

The "correct answer" for each case is written in SPECS' rtl field, purely for human reference --
the demo's equivalence verification uses the netlist itself as the gold standard (running iverilog against it), it does not look at this field.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

from refgen import Builder  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "netlists")


# ⚠ refgen's pitfall (learned the hard way): `ult`/`slt` return a **single wire name (str)**, not a list;
# `add` returns max(len)+1 bits; `const_mul` only accepts non-negative constants.


def d1_add3():
    """Sum of three numbers: the most basic shape for the solver's linear family."""
    b = Builder()
    for n in ("in1", "in2", "in3"):
        b.add_input(n, 8)
    s = b.add(b.add(b.port("in1"), b.port("in2")), b.port("in3"))
    b.set_output("out1", 10, s)
    return b


def d2_linear_const():
    """A linear expression with coefficients and a constant term: 3*in1 + 5*in2 + 7."""
    b = Builder()
    b.add_input("in1", 8)
    b.add_input("in2", 8)
    acc = b.add(b.const_mul(b.port("in1"), 3), b.const_mul(b.port("in2"), 5))
    acc = b.add(acc, b.const_val(7, 4))
    b.set_output("out1", 12, acc)
    return b


def d3_cmp_mux():
    """A comparison-driven mux: (in1 < in2) ? in3 : in4, unsigned comparison."""
    b = Builder()
    for n in ("in1", "in2", "in3", "in4"):
        b.add_input(n, 8)
    s = b.ult(b.port("in1"), b.port("in2"))       # str, not a list
    b.set_output("out1", 8, b.mux_bus(s, b.port("in3"), b.port("in4")))
    return b


def d4_macc():
    """Multiply-accumulate: in1 * in2 + in3. Multipliers make the netlist blow up fast, so narrow words are used deliberately."""
    b = Builder()
    b.add_input("in1", 6)
    b.add_input("in2", 6)
    b.add_input("in3", 12)
    b.set_output("out1", 13, b.add(b.mul(b.port("in1"), b.port("in2")), b.port("in3")))
    return b


def d5_shift_sub():
    """Shift and subtract: (in1 << 3) - in2. A shift produces no gates at the gate level, it's just wiring."""
    b = Builder()
    b.add_input("in1", 8)
    b.add_input("in2", 8)
    b.set_output("out1", 11, b.sub(b.shl(b.port("in1"), 3), b.zext(b.port("in2"), 11)))
    return b


SPECS = [
    ("d1_add3",        d1_add3,        "out1 = in1 + in2 + in3"),
    ("d2_linear_const", d2_linear_const, "out1 = 3*in1 + 5*in2 + 7"),
    ("d3_cmp_mux",     d3_cmp_mux,     "out1 = (in1 < in2) ? in3 : in4"),
    ("d4_macc",        d4_macc,        "out1 = in1 * in2 + in3"),
    ("d5_shift_sub",   d5_shift_sub,   "out1 = (in1 << 3) - in2"),
]


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, fn, rtl in SPECS:
        text = fn().emit("top")
        path = os.path.join(OUT, name + ".v")
        with open(path, "w") as f:
            f.write(f"// demo netlist: {rtl}\n")
            f.write("// Generated by demo/gen_netlists.py from tools/refgen.py, not organizer test data.\n")
            f.write(text)
        ngates = len(re.findall(
            r"\b(?:and|or|nand|nor|not|buf|xor|xnor)\s+\w+\s*\(", text))
        print(f"  {name:16s} {rtl:32s} {ngates:5d} gates -> {os.path.relpath(path, ROOT)}")


if __name__ == "__main__":
    main()
